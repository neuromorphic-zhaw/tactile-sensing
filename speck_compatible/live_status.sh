#!/bin/bash
# Live training dashboard -> rewrites LIVE_STATUS.md every 60s.
# Run:  nohup ./live_status.sh >/dev/null 2>&1 &
TS=/cfs/earth/scratch/matheron/tactile-sensing
SC=$TS/speck_compatible
OUT=$TS/LIVE_STATUS.md

variant_of() {   # map job name -> variant dir
  case "$1" in
    rawevent_*) echo "devin_rawevent/${1#rawevent_}" ;;
    5ms_*)      echo "devin_5ms/${1#5ms_}" ;;
    2ms_*)      echo "devin_2ms/${1#2ms_}" ;;
    1ms_*)      echo "devin_1ms/${1#1ms_}" ;;
    *)          echo "devin_10ms/${1}" ;;
  esac
}

while true; do
{
echo "# LIVE TRAINING DASHBOARD — $(date '+%Y-%m-%d %H:%M:%S')  (updates every 60s)"
echo
echo '```'
echo "## GPUs"
for nd in node301 node302; do
  tot=$([ "$nd" = node301 ] && echo 8 || echo 4)
  used=$(squeue -w $nd -t R --noheader -o "%D" | awk '{s+=$1} END{print s+0}')
  echo "  $nd: $((tot-used))/$tot free"
done
echo
echo "## RUNNING"
printf '  %-8s %-22s %-8s %-7s %-8s %-8s %-6s %-8s %s\n' JOBID JOB NODE EPOCH VAL BEST s/ep ETA_h ELAPSED
squeue -u matheron -t R -o "%i %j %N %M" --noheader | while read jid jname node elap; do
  f=$(find $SC -name "run_${jid}.out" 2>/dev/null | head -1)
  if [ -n "$f" ]; then
    line=$(grep "^Epoch" "$f" | tail -1)
    ep=$(echo "$line" | grep -oP 'Epoch \K[0-9]+' | head -1); tot=$(echo "$line" | grep -oP '/\K[0-9]+(?=/| )' | head -1)
    val=$(echo "$line" | grep -oP 'val \K[0-9.]+' | head -1); best=$(echo "$line" | grep -oP 'best \K[0-9.]+' | head -1)
    sec=$(echo "$line" | grep -oP '[0-9.]+(?=s)' | tail -1)
    if [ -n "$ep" ]; then
      eta=$(awk "BEGIN{printf \"%.1f\", ($tot-$ep)*$sec/3600}")
      printf '  %-8s %-22s %-8s %-7s %-8s %-8s %-6s %-8s %s\n' "$jid" "$jname" "$node" "$ep/$tot" "$val%" "$best%" "$sec" "$eta" "$elap"
    else
      printf '  %-8s %-22s %-8s %s\n' "$jid" "$jname" "$node" "(preflight/setup — first epoch pending)"
    fi
  else
    printf '  %-8s %-22s %-8s %s\n' "$jid" "$jname" "$node" "(starting — log not found)"
  fi
done
echo
echo "## PENDING — queue order (top = next in line)"
i=0
squeue -u matheron -t PD -o "%i %j %P %r" --noheader | while read jid jname part reason; do
  i=$((i+1)); vdir=$(variant_of "$jname")
  printf '  %2d. job %-8s %-22s %-8s %s   -> %s\n' "$i" "$jid" "$jname" "$part" "[$reason]" "$vdir"
done
echo
echo "## COMPLETED — final test accuracy (all sweeps)"
CUTOFF=83.3
for d in $SC/devin_10ms/*/ $SC/devin_5ms/*/ $SC/devin_2ms/*/ $SC/devin_1ms/*/ $SC/devin_rawevent/*/; do
  for o in "$d"run_*/run_*.out; do
    [ -f "$o" ] || continue
    fa=$(grep -oP 'FINAL UNBIASED TEST ACCURACY: \K[0-9.]+' "$o" | tail -1)
    bv=$(grep "^Epoch" "$o" | grep -oP 'best \K[0-9.]+' | sort -rn | head -1)
    [ -n "$fa" ] && printf '  %-52s v%-6s t%s\n' "$(basename ${d%/})" "$bv" "$fa"
  done
done | sort -t'v' -k2 -rn
echo
echo "## TOP-10 WATCH — finished runs scoring above cutoff ($CUTOFF mean v+t)"
for d in $SC/devin_5ms/*/ $SC/devin_2ms/*/ $SC/devin_1ms/*/ $SC/devin_rawevent/*/; do
  for o in "$d"run_*/run_*.out; do
    [ -f "$o" ] || continue
    fa=$(grep -oP 'FINAL UNBIASED TEST ACCURACY: \K[0-9.]+' "$o" | tail -1)
    bv=$(grep "^Epoch" "$o" | grep -oP 'best \K[0-9.]+' | sort -rn | head -1)
    [ -z "$fa" ] && continue
    mean=$(awk "BEGIN{printf \"%.2f\", ($bv+$fa)/2}")
    if awk "BEGIN{exit !($mean > $CUTOFF)}"; then
      ck=$(find "$(dirname "$o")" -name best_speck_fitting.pt | head -1)
      printf '  ** TOP10 CANDIDATE: %-40s v%s t%s mean %s  ckpt=%s\n' "$(basename ${d%/})" "$bv" "$fa" "$mean" "${ck:-none}"
    fi
  done
done
echo "  (copy qualifying ckpt into deploy_checkpoints/ and push — see README)"
echo '```'
echo
echo "_Generated by speck_compatible/live_status.sh — kill \$(pgrep -f live_status.sh) to stop_"
} > $OUT.tmp && mv $OUT.tmp $OUT
sleep 60
done
